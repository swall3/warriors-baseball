// Generates src/lib/scenarioCatalog.ts — the CLIENT-SAFE projection of the
// BACKUP_SCENARIOS pool. Only non-answer fields are emitted (id, label,
// category, runners, ballZone, ballReachesTarget). The answer fields
// (question, targetZone, explanation) stay server-only in gameData.ts.
//
// Run: node scripts/gen-scenario-catalog.mjs
// gameData.ts is the source of truth; re-run this after editing scenarios.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "src/lib/gameData.ts");
const out = join(root, "src/lib/scenarioCatalog.ts");

// Load BACKUP_SCENARIOS by evaluating the array literal in isolation. We slice
// the `export const BACKUP_SCENARIOS: BackupScenario[] = [ ... ];` block and
// parse it as JS so we never hand-maintain a parallel copy.
const text = readFileSync(src, "utf8");
const start = text.indexOf("export const BACKUP_SCENARIOS");
if (start === -1) throw new Error("BACKUP_SCENARIOS not found in gameData.ts");
// Skip past the `= ` assignment so we don't grab the `[]` in the type annotation.
const eq = text.indexOf("=", start);
const open = text.indexOf("[", eq);
// find matching closing bracket for the array
let depth = 0;
let end = -1;
for (let i = open; i < text.length; i++) {
  const c = text[i];
  if (c === "[") depth++;
  else if (c === "]") {
    depth--;
    if (depth === 0) {
      end = i;
      break;
    }
  }
}
if (end === -1) throw new Error("Could not find end of BACKUP_SCENARIOS array");
const arrayLiteral = text.slice(open, end + 1);
// eslint-disable-next-line no-eval
const scenarios = eval(`(${arrayLiteral})`);

const SAFE_KEYS = ["id", "label", "category", "runners", "ballZone", "ballReachesTarget"];
const catalog = scenarios.map((s) => {
  const e = {};
  for (const k of SAFE_KEYS) if (s[k] !== undefined) e[k] = s[k];
  return e;
});

// Per-position bundle SUMMARIES. Membership is derived from ballZone +
// targetZone (targetZone is an ANSWER field), so we compute it here at
// generation time but emit only AGGREGATES — a scenario count and per-category
// counts. We deliberately do NOT emit the scenarioId lists: because membership
// == {ballZone, targetZone}, a client holding both the catalog (which has
// ballZone) and the id lists could recover every targetZone. Aggregates can't
// identify individual scenarios, so they are safe to ship to the client.
const POSITIONS = ["P", "C", "1B", "2B", "3B", "SS", "LF", "CF", "RF"];
const CATEGORIES = ["cover", "backup", "relay", "miss_recovery"];
const bundleSummaries = {};
for (const position of POSITIONS) {
  const members = scenarios.filter(
    (s) => s.ballZone === position || s.targetZone === position,
  );
  if (members.length === 0) continue;
  const categoryCounts = Object.fromEntries(CATEGORIES.map((c) => [c, 0]));
  for (const s of members) categoryCounts[s.category] += 1;
  bundleSummaries[position] = { scenarioCount: members.length, categoryCounts };
}

const body = `// GENERATED by scripts/gen-scenario-catalog.mjs — DO NOT EDIT BY HAND.
// Client-safe projection of BACKUP_SCENARIOS: non-answer fields only.
// Answer fields (question, targetZone, explanation) live server-only in gameData.ts.
import type { ScenarioCategory, FieldZone, ScenarioCatalogEntry } from "./scenarioTypes.ts";

export const SCENARIO_CATALOG: ScenarioCatalogEntry[] = ${JSON.stringify(catalog, null, 2)};

export const SCENARIO_CATALOG_BY_ID: Record<string, ScenarioCatalogEntry> =
  Object.fromEntries(SCENARIO_CATALOG.map((s) => [s.id, s]));

// Per-position bundle summaries (AGGREGATES ONLY — no scenarioId lists, so no
// targetZone can be recovered). Derived from ballZone + targetZone at
// generation time.
export type BundleSummary = {
  scenarioCount: number;
  categoryCounts: Record<ScenarioCategory, number>;
};
export const BUNDLE_SUMMARIES: Partial<Record<FieldZone, BundleSummary>> =
  ${JSON.stringify(bundleSummaries, null, 2)};
`;

writeFileSync(out, body);
console.log(`Wrote ${out} with ${catalog.length} entries.`);
